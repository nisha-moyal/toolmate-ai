import os
import sys
import json

import httpx
import redis
from fastapi import FastAPI
from groq import Groq
from pydantic import BaseModel

app = FastAPI(title="ToolMate Agent")

GROQ_API_KEY = os.getenv("GROQ_API_KEY", "").strip()

if not GROQ_API_KEY:
    sys.exit("[ToolMate Agent] GROQ_API_KEY is missing.")

llm = Groq(api_key=GROQ_API_KEY)

# --- Service addresses: SERVICE NAMES, not IPs (Compose networking) ---------
# redis-py connects lazily (only on first command), so no retry loop needed:
# by the time the first /chat request arrives, Redis is long since ready.
r = redis.Redis(
    host=os.getenv("REDIS_HOST", "redis"),
    port=6379,
    decode_responses=True,
)

TOOLS_URL = os.getenv("TOOLS_URL", "http://tools:7000")

# --- The tool menu we show the LLM ------------------------------------------
# Each entry describes one tool: its name, what it does, and what inputs
# it expects. The LLM reads these descriptions to decide when to use them.
TOOL_DEFS = [
    {
        "type": "function",
        "function": {
            "name": "calculator",
            "description": "Evaluate a math expression, e.g. '23*47' or '(100-8)/4'",
            "parameters": {
                "type": "object",
                "properties": {"expression": {"type": "string"}},
                "required": ["expression"],
            },
        },
    },
    {
        "type": "function",
        "function": {
            "name": "get_datetime",
            "description": "Get the current date and time",
            "parameters": {"type": "object", "properties": {}},
        },
    },
]

def call_tool(tool_name: str, tool_args: dict) -> str:
    """
    Call a tool by name, passing the given arguments. Return the tool's output as a string.
    """
    if tool_name == "calculator":
        # Call the calculator tool
        response = httpx.post(f"{TOOLS_URL}/calculator", json=tool_args)
        response.raise_for_status()
        return response.json()["result"]
    elif tool_name == "get_datetime":
        # Call the get_datetime tool
        response = httpx.get(f"{TOOLS_URL}/datetime")
        response.raise_for_status()
        return response.json()["now"]
    else:
        raise ValueError(f"Unknown tool: {tool_name}")

class ChatRequest(BaseModel):
    session_id: str
    message: str

@app.get("/")
def health():
    return {
        "status": "ToolMate Agent is live 🤖",
        "tools_url": TOOLS_URL,
        "redis_host": os.getenv("REDIS_HOST", "redis"),
    }

@app.post("/chat")
def chat(req: ChatRequest):
    """
    Handle a chat request. The request includes a session ID and a message.
    The response is generated by the LLM, which may call tools as needed.
    """
    # Retrieve the conversation history from Redis
    history_key = f"history:{req.session_id}"
    history = [json.loads(msg) for msg in r.lrange(history_key, 0, -1)]
    history.append({"role": "user", "content": req.message})

    # Call the LLM to generate a response
    message = None
    for _ in range(3):  # Allow up to 3 iterations of think-act-observe
        resp = llm.chat.completions.create(
                model="openai/gpt-oss-120b",
                messages=history,
                tools=TOOL_DEFS,
            
            )

        message = resp.choices[0].message

        if not message.tool_calls:
            # No tool calls, we're done
            break

        # The LLM requested to call one or more tools
        history.append(message.model_dump(exclude_none=True))
        for tool_call in message.tool_calls:
            tool_name = tool_call.function.name
            tool_args = json.loads(tool_call.function.arguments)
            tool_result = call_tool(tool_name, tool_args)
            history.append(
                {
                    "role": "tool",
                    "tool_call_id": tool_call.id,
                    "content": json.dumps(tool_result),
                }
            )

    # Save the updated conversation history back to Redis
    history.append({"role": "assistant", "content": message.content})
    r.delete(history_key)
    for msg in history:
        r.rpush(history_key, json.dumps(msg))

    return {"response": message.content}
